// Builds ../morph_data.js: the true outline morph of נ into ל (Frank Ruhl Libre 500, the Shorts face), for KIT.STACK's "נ became ל" moment.
// Both glyphs are single contours. Each is centred on its own advance width, so a frame drawn at (x, baseline) sits exactly where
// fillText(letter, x, baseline) with textAlign 'center' puts the letter. Units: 1000 per em (scale by size / 1000 when drawing).
// Usage: cd engine && npm i && node mk_morph.cjs
const fs = require('fs'), path = require('path'), opentype = require('opentype.js'), flubber = require('flubber');
const buf = fs.readFileSync(path.join(__dirname, 'fonts/FrankRuhlLibre-Medium.ttf'));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.length));
const glyphPath = ch => { const g = font.charToGlyph(ch); return g.getPath(-g.advanceWidth / 2, 0, 1000).toPathData(2); };
const A = glyphPath('נ'), B = glyphPath('ל'), N = 48;
const interp = flubber.interpolate(A, B, { maxSegmentLength: 10 });
const frames = []; for (let i = 0; i <= N; i++) frames.push((i === 0 ? A : i === N ? B : interp(i / N)).replace(/-?\d+\.\d+/g, m => String(Math.round(+m))));
fs.writeFileSync(path.join(__dirname, '../morph_data.js'),
  '// Generated by engine/mk_morph.cjs: outline morph נ → ל, Frank Ruhl Libre 500, 1000 units per em, centred on the advance width.\n' +
  'KIT.MORPH_DATA = ' + JSON.stringify({ upm: 1000, from: 'נ', to: 'ל', frames }) + ';\n');
console.log('frames', frames.length, 'bytes', fs.statSync(path.join(__dirname, '../morph_data.js')).size);
